target("usd-viewer-lib")
    set_kind("static")
    add_files("*.cpp", "*.cppm")
    remove_files("main.cpp")
    add_files("viewer.cpp", "options.cpp", "scene.cpp", "camera.cpp", "usd-viewer.cppm", {public = true})
    add_deps("engine", "hitagi_editor")

target("usd-viewer-ui")
    set_kind("phony")
    add_packages("pocketjs")
    add_rules("@pocketjs/ui")
    set_values("pocketjs.entry", "examples/usd-viewer/ui/usd-viewer.tsx")
    set_values("pocketjs.density", 2)

target("usd-viewer")
    set_kind("binary")
    add_files("main.cpp")
    add_deps("usd-viewer-lib", "usd-viewer-ui")
    set_rundir("$(projectdir)")

target("usd-viewer-e2e")
    set_kind("binary")
    set_group("test")
    add_files("test/e2e.cpp")
    add_deps("usd-viewer-lib", "usd-viewer-ui")
    set_rundir("$(projectdir)")
